//显示错误弹出对话框
function ShowErrorBox(error_id)
{
    if(error_id==-1)
        MessageText=Lang["Error_71"];
    else
    {
        if(error_id>=1 && error_id<=10000)
            MessageText=ErrorList1[error_id];
        else
            MessageText=ErrorList2[error_id-10000];
    }
    ShowPopUp("0");
    CanEnterPop=1;
}

//显示一个提示信息
function ShowMessageBox(message)
{
    MessageText=message;
    ShowPopUp("0");
    CanEnterPop=1;
}
